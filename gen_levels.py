def generate_crossword_level(level_id, words, grid_size=5):
    """Генерирует уровень кроссворда с заданными словами"""
    grid = [['' for _ in range(grid_size)] for _ in range(grid_size)]
    placed_words = []
    intersections = {}
    
    # Сортируем слова по длине (от длинных к коротким)
    sorted_words = sorted(words, key=len, reverse=True)
    
    for word in sorted_words:
        placed = False
        attempts = 0
        
        while not placed and attempts < 100:
            attempts += 1
            
            # Определяем направление
            direction = random.choice(['horizontal', 'vertical'])
            
            # Если горизонтальное, проверяем помещается ли в строку
            if direction == 'horizontal':
                row = random.randint(0, grid_size - 1)
                col = random.randint(0, grid_size - len(word))
                
                # Проверяем пересечения
                valid_position = True
                for i, letter in enumerate(word):
                    if grid[row][col + i] != '' and grid[row][col + i] != letter:
                        valid_position = False
                        break
                
                if valid_position:
                    # Проверяем, не пересекается ли с другими словами по бокам
                    if col > 0 and grid[row][col - 1] != '':
                        continue
                    if col + len(word) < grid_size and grid[row][col + len(word)] != '':
                        continue
                    
                    # Размещаем слово
                    for i, letter in enumerate(word):
                        grid[row][col + i] = letter
                    
                    placed_words.append({
                        'word': word.upper(),
                        'start': [row, col],
                        'direction': direction,
                        'hint': get_hint(word)
                    })
                    placed = True
                    
                    # Запоминаем пересечения
                    for i, letter in enumerate(word):
                        if grid[row][col + i] != '':
                            intersections[f"{row}-{col + i}"] = letter
    
    return grid, placed_words, intersections

