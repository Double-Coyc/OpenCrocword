def generate_levels():
    """Генерирует 25 уровней кроссворда"""
    levels = []
    
    for i in range(25):
        # Выбираем случайные слова для уровня
        num_words = random.randint(2, 4)
        level_words = random.sample(russian_words, num_words)
        
        # Генерируем уровень
        grid_size = random.randint(5, 7)
        grid, words, intersections = generate_crossword_level(i + 1, level_words, grid_size)
        
        # Определяем сложность
        difficulty = "easy"
        if len(level_words) >= 3 and grid_size >= 6:
            difficulty = "medium"
        if len(level_words) >= 4 and grid_size >= 7:
            difficulty = "hard"
        
        # Определяем награду
        reward = 50 + (i * 10) + ({"easy": 0, "medium": 25, "hard": 50}[difficulty])
        
        # Создаем бонусные слова
        bonus_words = []
        if difficulty != "easy":
            bonus_count = random.randint(1, 3)
            bonus_words = random.sample([w for w in russian_words if len(w) >= 4 and w not in level_words], bonus_count)
        
        level = {
            "id": i + 1,
            "name": f"Уровень {i + 1}",
            "grid": grid,
            "words": words,
            "reward": reward,
            "difficulty": difficulty,
            "bonusWords": bonus_words
        }
        
        levels.append(level)
    
    return {"levels": levels}

